def tr(language: LanguageCode, key: str, **values: object) -> str:
    template = TEXT.get(language, TEXT[DEFAULT_LANGUAGE]).get(key, TEXT["en-US"].get(key, key))
    return template.format(**values)


def mode_label(mode: UserMode, language: LanguageCode) -> str:
    if mode is UserMode.OPERATOR:
        return tr(language, "mode.operator")
    return tr(language, "mode.advanced_admin")


def server_status_label(server: ServerState, language: LanguageCode) -> str:
    if server.error:
        return tr(language, "server.status.error")
    if server.starting:
        return tr(language, "server.status.starting")
    if server.running:
        return tr(language, "server.status.running")
    return tr(language, "server.status.stopped")
